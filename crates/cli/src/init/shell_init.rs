//! `playbook shell-init`: a `playbook` shell function, printed for the rc file
//! to `eval`. It only adds the `cd` into a worktree after `playbook cc` and
//! `playbook ccd`; every other call runs the binary untouched. There is no
//! `cc`, `ccc` or `ccd` function, so nothing shadows the C compiler.
//!
//! With `launcher.claudeOverride` on, the output also defines a `claude`
//! function that calls the launcher only for a plain interactive session
//! (see `claude_override.sh`); every other call runs the real binary untouched.
//!
//! With `launcher.shortName` on, the output also defines `pb` as a short name
//! for `playbook`, but only when nothing else uses that name (see `short_name.sh`).
//!
//! The launcher itself is `playbook cc` (`playbook cc launch`). A child process cannot change
//! its parent's directory, so the function hands the binary a temp file in
//! `$PLAYBOOK_CC_CD_FILE`; when the launcher enters a worktree it writes the
//! path there, and the function `cd`s to it after the session. One line, no
//! stdout parsing, and the session keeps the terminal.

use super::shim::ShellKind;

/// The function bodies are valid in bash and zsh alike, so the one text is
/// shared; only the header names the shell it was generated for.
pub fn script(shell: ShellKind) -> String {
    script_with(shell, false)
}

/// The text `shell-init` prints for the current config.
pub fn script_for_config(shell: ShellKind, home: &std::path::Path) -> String {
    script_with_options(
        shell,
        claude_override_enabled(home),
        short_name_enabled(home),
    )
}

/// Whether `launcher.shortName` is on. Off unless the user chose it.
pub fn short_name_enabled(home: &std::path::Path) -> bool {
    matches!(
        crate::config::resolve("launcher.shortName", home, None),
        Ok((serde_json::Value::Bool(true), _))
    )
}

/// The first executable file called `name` in the directories of `path`, the
/// way a shell would find a command. Used by `init` to see whether `pb` is taken.
pub fn command_on_path(name: &str, path: &std::ffi::OsStr) -> Option<std::path::PathBuf> {
    std::env::split_paths(path)
        .map(|dir| dir.join(name))
        .find(|p| p.metadata().is_ok_and(|m| m.is_file() && is_executable(&m)))
}

#[cfg(unix)]
fn is_executable(meta: &std::fs::Metadata) -> bool {
    use std::os::unix::fs::PermissionsExt;
    meta.permissions().mode() & 0o111 != 0
}

#[cfg(not(unix))]
fn is_executable(_meta: &std::fs::Metadata) -> bool {
    true
}

/// Whether `launcher.claudeOverride` is on. Off unless the user chose it.
pub fn claude_override_enabled(home: &std::path::Path) -> bool {
    matches!(
        crate::config::resolve("launcher.claudeOverride", home, None),
        Ok((serde_json::Value::Bool(true), _))
    )
}

/// The same text with the optional `claude` function appended when `claude_override` is set.
pub fn script_with(shell: ShellKind, claude_override: bool) -> String {
    script_with_options(shell, claude_override, false)
}

/// The same text with each optional part appended when its flag is set.
pub fn script_with_options(shell: ShellKind, claude_override: bool, short_name: bool) -> String {
    let mut text = base(shell);
    if claude_override {
        text.push_str(CLAUDE_OVERRIDE);
    }
    if short_name {
        text.push_str(SHORT_NAME);
    }
    text
}

/// The optional `pb` function, defined only when the name is free.
pub const SHORT_NAME: &str = include_str!("short_name.sh");

/// The optional `claude` function and its bypass rules.
pub const CLAUDE_OVERRIDE: &str = include_str!("claude_override.sh");

fn base(shell: ShellKind) -> String {
    let name = match shell {
        ShellKind::Bash => "bash",
        ShellKind::Zsh => "zsh",
    };
    format!(
        r#"# playbook launcher for {name}, generated by `playbook shell-init`
_playbook_cc() {{
  local _pb_cd _pb_dir _pb_rc
  _pb_cd="$(mktemp "${{TMPDIR:-/tmp}}/playbook-cc.XXXXXX" 2>/dev/null)" || _pb_cd=""
  PLAYBOOK_CC_CD_FILE="$_pb_cd" command playbook cc launch "$@"
  _pb_rc=$?
  if [ -n "$_pb_cd" ]; then
    if [ -s "$_pb_cd" ]; then
      IFS= read -r _pb_dir < "$_pb_cd" && [ -d "$_pb_dir" ] && cd "$_pb_dir"
    fi
    rm -f "$_pb_cd"
  fi
  return $_pb_rc
}}
function playbook {{
  case "${{1-}}" in
    ccd) shift; _playbook_cc --skip-permissions -- "$@" ;;
    cc)
      shift
      case "${{1-}}" in
        launch) shift; _playbook_cc "$@" ;;
        list|ls|prune|bust-cache|worktree|new|housekeep|help|-h|--help) command playbook cc "$@" ;;
        *) _playbook_cc -- "$@" ;;
      esac
      ;;
    *) command playbook "$@" ;;
  esac
}}
_playbook_moved() {{ echo "$1 moved into playbook: run \`playbook $2\` (or \`pb $2\`)" >&2; return 127; }}
type ccc >/dev/null 2>&1 || eval 'ccc() {{ _playbook_moved ccc cc; }}'
type ccd >/dev/null 2>&1 || eval 'ccd() {{ _playbook_moved ccd ccd; }}'
"#
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_shells_define_a_playbook_wrapper_and_no_old_launchers() {
        for kind in [ShellKind::Bash, ShellKind::Zsh] {
            // Arrange and act
            let text = script(kind);

            // Assert
            assert!(text.contains("\nfunction playbook {"));
            assert!(!text.contains("\nccc() {"));
            assert!(!text.contains("\nccd() {"));
            assert!(!text.contains("\ncc() {"));
            assert!(!text.contains("pb()"));
        }
    }

    #[test]
    fn wrapper_routes_ccd_with_skip_permissions() {
        // Arrange and act
        let text = script(ShellKind::Zsh);

        // Assert
        assert!(text.contains("ccd) shift; _playbook_cc --skip-permissions -- \"$@\""));
    }
}
